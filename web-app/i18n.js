  let lang = "en";

  function setLang(value) {
    lang = value === "ar" ? "ar" : "en";
  }

  // Unicode isolate marks, built from code points so the source stays plain ASCII here.
  const FSI = String.fromCharCode(0x2068);
  const PDI = String.fromCharCode(0x2069);
  const ISOLATES = new RegExp(`[${String.fromCharCode(0x2066)}-${PDI}]`, "g");

  function t(key, params = {}) {
    const entry = STRINGS[key];
    if (!entry) throw new Error(`Missing string: ${key}`);
    const text = entry[lang === "ar" ? 1 : 0];
    // In Arabic, each inserted value is wrapped in first-strong isolate marks (U+2068, U+2069)
    // so values such as $43,200.00 or LOC/FP keep their own direction inside Arabic text.
    const wrap = (value) => (lang === "ar" ? FSI + value + PDI : value);
    return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? wrap(String(params[name])) : match));
  }

  const ar = () => lang === "ar";

  // Course data lookups. Each falls back to English when there is no Arabic entry.
  const course = {
    gscQuestion: (index, english) => (ar() ? COURSE_AR.gscQuestions[index] : english),
    characteristic: (name) => (ar() && COURSE_AR.characteristics[name] ? COURSE_AR.characteristics[name][0] : name),
    characteristicDesc: (name, english) => (ar() && COURSE_AR.characteristics[name] ? COURSE_AR.characteristics[name][1] : english),
    rating: (index, english) => (ar() ? COURSE_AR.ratingScale[index] : english),
    fpLabel: (key, english) => (ar() ? COURSE_AR.fpLabels[key] : english),
    language: (name) => (ar() && COURSE_AR.languages[name] ? COURSE_AR.languages[name] : name),
    modeLabel: (mode, english) => (ar() ? COURSE_AR.modeLabels[mode] : english),
    modeNote: (mode, english) => (ar() ? COURSE_AR.modeNotes[mode] : english),
    driver: (index, english) => (ar() ? COURSE_AR.drivers[index] : english),
    driverRating: (rating) => (ar() ? COURSE_AR.ratings[rating] : rating),
    driverGroup: (index, english) => (ar() ? COURSE_AR.driverGroups[index] : english),
    delphiStep: (index, english) => (ar() ? COURSE_AR.delphiSteps[index] : english),
    tableTitle: (number, english) => (ar() ? COURSE_AR.tableTitles[number - 1] : english),
    tableNote: (number, english) => (ar() ? COURSE_AR.tableNotes[number - 1] : english),
    task: (name) => (ar() && COURSE_AR.tasks[name] ? COURSE_AR.tasks[name] : name),
  };

  // Applies data-i18n (text) and data-i18n-attr ("attr:key;attr:key") to static markup.
  function applyStatic(rootNode) {
    rootNode.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    rootNode.querySelectorAll("[data-i18n-attr]").forEach((el) => {
      el.dataset.i18nAttr.split(";").forEach((pair) => {
        const [attr, key] = pair.split(":");
        el.setAttribute(attr.trim(), t(key.trim()));
      });
    });
  }

  // Removes the isolate marks, for text that leaves the page (clipboard, CSV).
  const plain = (text) => String(text).replace(ISOLATES, "");

  return { STRINGS, COURSE_AR, setLang, t, plain, course, applyStatic, getLang: () => lang };
